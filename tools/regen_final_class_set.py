#!/usr/bin/env python3
"""Regenerate schemas/V_eta_final_class_set.md from the BUILT schema's index.json.

The final class set is derived, never hand-authored -- tools/gates.py runs
this, so the doc never drifts from the schema. Categories (fixed order):
  (1) spine & genus  (2) entities  (3) composites (value)
  (4) data-type leaf tier  (5) time_reference family  (6) data_body (exactly 2)
  (7) acquisition & infra.
Non-persist classes are listed under "NOT in the final set" by disposition.
"""
import json
import os
from pathlib import Path

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
INDEX = os.path.join(ROOT, "schemas", "did_v2", "index.json")
REGISTRY = os.path.join(ROOT, "schemas", "did_v2", "stable",
                        "binding_registry_meta.json")
OUT = os.path.join(ROOT, "schemas", "V_eta_final_class_set.md")

# The abstract spine & genus (category 1) -- named explicitly; everything else is
# classified by its superclass chain. `entity` is NOT spine: since the one-entity
# schema (V_eta_entity_composition_plan.md) it is the one entity class, so it is
# category (2), and the kinds of entity are rows of `entity_type_bindings`.
SPINE = {
    "app", "base", "data", "data_body", "value", "directed_relation",
    "relation", "assertion", "calculation", "interaction",
    "manipulation", "observation", "statement",
    "undirected_relation",
}


def main():
    idx = json.loads(Path(INDEX).read_text())
    by_name = {s["class_name"]: s for s in idx["schemas"] if not s.get("is_meta")}

    def chain(name, seen=None):
        seen = seen if seen is not None else set()
        s = by_name.get(name)
        if not s:
            return seen
        for sup in s.get("superclasses", []):
            n = sup.get("class_name") if isinstance(sup, dict) else sup
            if n and n not in seen:
                seen.add(n)
                chain(n, seen)
        return seen

    cats = {k: [] for k in
            ("spine", "entity", "composite", "leaf", "timeref", "body", "infra")}
    dropped = {}  # disposition -> [names]
    for name, s in by_name.items():
        if s.get("disposition") != "persist":
            dropped.setdefault(s.get("disposition", "?"), []).append(name)
            continue
        ch = chain(name)
        if name in SPINE:
            cats["spine"].append(name)
        elif "time_reference" in ch or name == "time_reference":
            cats["timeref"].append(name)
        elif "data_body" in ch:
            cats["body"].append(name)
        elif ch & {"observation", "manipulation", "assertion",
                   "calculation"}:
            cats["leaf"].append(name)
        elif "relation" in ch:
            # A relation LEAF that happens to inherit a data type (clock_alignment
            # is [relation, polynomial]) is a statement between documents, not a
            # value type: it sits with its sync-infra siblings, not in (3).
            # Added 2026-09-25 after the #73 audit found it listed as a composite.
            cats["infra"].append(name)
        elif "value" in ch:
            cats["composite"].append(name)
        elif name == "entity" or "entity" in ch:
            cats["entity"].append(name)
        else:
            cats["infra"].append(name)

    for v in cats.values():
        v.sort()
    for v in dropped.values():
        v.sort()
    total = sum(len(v) for v in cats.values())

    def joined(names):
        return ", ".join(f"`{n}`" for n in names)

    lines = []
    lines.append(f"# V_eta — The Final Class Set ({total} persist)")
    lines.append("")
    lines.append("*Generated by `tools/regen_final_class_set.py` from the built "
                 "schema's `index.json` (disposition markers) — do NOT hand-edit; "
                 "re-run `tools/gates.py` after a class change. Category order: spine → entities → "
                 "composites (value) → leaves → time_reference → data_body "
                 "(exactly 2) → infra.*")
    lines.append("")
    lines.append("| Category | n |")
    lines.append("|---|--:|")
    order = [("spine", "① Statement spine & genus"), ("entity", "② Entities"),
             ("composite", "③ Quantity & substance composites (value)"),
             ("leaf", "④ Data-type leaf tier"), ("timeref", "⑤ time_reference family"),
             ("body", "⑥ data_body family"),
             ("infra", "⑦ Acquisition & infra (keep)")]
    for key, label in order:
        lines.append(f"| {label} | {len(cats[key])} |")
    lines.append(f"| **Persist total** | **{total}** |")
    lines.append("")
    types = []
    if os.path.exists(REGISTRY):
        types = [r["type"] for r in json.loads(Path(REGISTRY).read_text())
                 .get("entity_type_bindings", [])]
    for key, label in order:
        lines.append(f"## {label} ({len(cats[key])})")
        lines.append(joined(cats[key]) or "*(none)*")
        if key == "entity" and types:
            # Plain text, not backticked: these are values of entity.type, not
            # classes, and the viewer reads every backticked name here as a class.
            lines.append("")
            lines.append(f"Kinds of entity ({len(types)}, the values of entity.type in "
                         "entity_type_bindings): " + ", ".join(types) + ".")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## NOT in the final set (by disposition)")
    lines.append("")
    for disp in sorted(dropped):
        lines.append(f"**{disp} ({len(dropped[disp])}):**")
        lines.append(joined(dropped[disp]))
        lines.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"regenerated {OUT}: {total} persist "
          f"({', '.join(f'{k}={len(v)}' for k, v in cats.items())}); "
          f"dropped {sum(len(v) for v in dropped.values())} "
          f"({', '.join(f'{k}={len(v)}' for k, v in dropped.items())})")


if __name__ == "__main__":
    main()
