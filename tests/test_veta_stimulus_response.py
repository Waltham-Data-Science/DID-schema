def test_freq_response_is_a_harmonic_number_not_a_boolean():
    """REPAIR 4 of the signed plan, and the last one of the five to be built.

    The field was `integer {min: 0, max: 1}`, documented "1 if this scalar
    response is a frequency-domain measurement, 0 otherwise". It is the HARMONIC
    INDEX. tuning_response.m:202 sweeps `freq_response_commands = [0 1 2]` by
    default, :260 assigns one per document and :262-266 turns it into
    'mean' | 'F1' | 'F2' -- so `max: 1` is a claim that would reject roughly a
    third of the class.

    TWO errors, and the second is why nothing broke: `+did2/+schema/cache.m`
    validateConstraints (:1340) switches on
    maxLength|minLength|minimum|maximum|enum and silently tolerates anything
    else, so `min`/`max` were INERT and never enforced. Fixing only the spelling
    would have quarantined every F2 document."""
    _tier, d = BUILT["stimulus_response_scalar_parameters_basic"]
    f = _field(d, "freq_response")
    c = f.get("constraints") or {}
    assert "max" not in c and "min" not in c, "the inert spelling is back: %r" % c
    assert c.get("minimum") == 0
    # NO maximum. :207 is `freq_response_commands = freq_response`, straight from
    # the caller, so 3 is representable; a bound we cannot derive from the writer
    # is the invention this repair track exists to remove.
    assert "maximum" not in c
    assert "0 otherwise" not in f["documentation"]
    assert "harmonic" in f["documentation"].lower()


def test_isspike_is_left_alone_and_the_inert_spelling_is_counted():
    """DENOMINATOR: 241 built schema files walked (4 meta sidecars skipped).

    `isspike` is equally inert but its INTENT is correct -- the writer sets 0 or
    1 and nothing else (:176, :179-182) -- so rewriting its key would newly
    ENFORCE a rule on 11,440 live documents to no benefit. Pinned so the count
    of inert declarations is a number somebody chose, not one nobody noticed."""
    inert = []
    walked = 0

    def walk(fields, cls, prefix):
        for f in fields:
            c = f.get("constraints") or {}
            if "min" in c or "max" in c:
                inert.append("%s.%s%s" % (cls, prefix, f["name"]))
            if f.get("fields"):
                walk(f["fields"], cls, prefix + f["name"] + ".")

    for path in sorted(glob.glob(os.path.join(VETA, "*", "*.json"))):
        with open(path) as fh:
            d = json.load(fh)
        if "document_class" not in d:
            continue
        walked += 1
        walk(d.get("fields", []), d["document_class"]["class_name"], "")

    assert walked == 241, "schema count moved; re-derive the inert set (%d)" % walked
    assert sorted(inert) == [
        "element.direct",
        "element.reference",
        "stimulus_response_scalar_parameters_basic.isspike",
    ]


