import glob
import json
import os

import pytest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VETA = os.path.join(REPO_ROOT, "schemas", "V_eta")
GROUND_TRUTH = os.path.join(REPO_ROOT, "schemas", "V_eta_ndi_ground_truth.json")

FAMILY = (
    "stimulus_response",
    "stimulus_response_scalar",
    "stimulus_response_scalar_parameters",
    "stimulus_response_scalar_parameters_basic",
)


def _built():
    """class_name -> (tier, schema dict) for every built V_eta schema."""
    out = {}
    for path in sorted(glob.glob(os.path.join(VETA, "*", "*.json"))):
        with open(path) as fh:
            d = json.load(fh)
        if "document_class" not in d:
            continue  # the meta/registry sidecars
        out[d["document_class"]["class_name"]] = (
            os.path.basename(os.path.dirname(path)),
            d,
        )
    return out


BUILT = _built()

with open(GROUND_TRUTH) as _fh:
    NDI = json.load(_fh)["classes"]


def _dep_names(schema):
    return {d["name"] for d in schema.get("depends_on", [])}


def _field(schema, name):
    for f in schema.get("fields", []):
        if f["name"] == name:
            return f
    raise AssertionError(
        "%s has no field %r; it has %r"
        % (schema["document_class"]["class_name"], name,
           [f["name"] for f in schema.get("fields", [])])
    )


# ---------------------------------------------------------------- the targets

def test_harmonic_component_is_an_abstract_data_type_composite():
    """The composite half of the signed pair. ABSTRACT: a bare harmonic is never
    a document, only the direction leaf is."""
    tier, d = BUILT["harmonic_component"]
    assert tier == "draft"
    assert d["document_class"].get("abstract") is True
    assert [s["class_name"] for s in d["document_class"]["superclasses"]] == ["data_type"]
    # T14: ONE `value` slot, structure, not a bag of loose top-level fields.
    assert [f["name"] for f in d["fields"]] == ["value"]
    assert d["fields"][0]["type"] == "structure"


def test_the_value_cell_carries_the_five_signed_subfields():
    """As signed: {harmonic (0=DC, 1=F1, 2=F2), real, imaginary, control_real,
    control_imaginary}. The CONTROL pair is the half V_eta previously had no home
    for at all -- `control_response_real[]` is meaningless without it."""
    _tier, d = BUILT["harmonic_component"]
    subs = {s["name"]: s for s in _field(d, "value")["fields"]}
    assert set(subs) == {"harmonic", "real", "imaginary",
                         "control_real", "control_imaginary"}


def test_the_four_coefficient_subfields_are_matrices_and_harmonic_is_scalar():
    """One coefficient PER READING, not one per document. The writer fills these
    from a column -- one row per stimulus presentation
    (tuning_response.m:309-313) -- so a real document carries as many
    coefficients as it has readings.

    This was built as scalar `double` and corrected 2026-08-10. It had not bitten
    because +did2/+schema/cache.m validates a block's TOP-LEVEL fields and never
    recurses into a structure's sub-fields, so a wrong sub-field type is
    unenforced today; it would have surfaced the moment sub-field validation
    landed, against documents already written in the wrong shape.

    `harmonic` stays scalar: there is exactly one harmonic number per component,
    which is what makes the component a component."""
    _tier, d = BUILT["harmonic_component"]
    subs = {s["name"]: s for s in _field(d, "value")["fields"]}
    for name in ("real", "imaginary", "control_real", "control_imaginary"):
        assert subs[name]["type"] == "matrix", name
        assert subs[name]["mustBeScalar"] is False, name
    assert subs["harmonic"]["type"] == "integer"
    assert subs["harmonic"]["mustBeScalar"] is True


def test_harmonic_component_calculation_is_the_subject_calculation_leaf():
    """Mirrors tuning_curve / tuning_curve_calculation exactly. The tier is
    `subject_calculation` because this is computed, and because
    `stimulus_tuningcurve` -- the other output of the same app and the same file
    -- already folds to a calculation leaf. Treating two outputs of one app
    differently would be drift by our own definition."""
    _tier, d = BUILT["harmonic_component_calculation"]
    assert [s["class_name"] for s in d["document_class"]["superclasses"]] == [
        "subject_calculation", "harmonic_component"]
    assert d["document_class"].get("abstract") is not True
    # It declares NO edges of its own: subject_id / time_reference_# /
    # instrument_id / software_id / method_parameters_id / derived_from_# all
    # arrive from the subject_statement -> subject_interaction -> subject_calculation
    # chain. Re-declaring any of them here is the duplicate-declaration defect.
    assert d.get("depends_on", []) == []


def test_the_leaf_inherits_every_edge_the_fold_writes():
    """The migrator writes subject_id, time_reference_1, instrument_id,
    derived_from_1, derived_from_2 and method_parameters_id. Each must be
    declared SOMEWHERE in the ancestor chain, or the fold is writing edges the
    schema does not know about."""
    chain = ["subject_statement", "subject_interaction", "subject_calculation"]
    declared = set()
    for cls in chain:
        declared |= _dep_names(BUILT[cls][1])
    assert {"subject_id", "time_reference_#", "instrument_id",
            "method_parameters_id", "derived_from_#"} <= declared
    # derived_from_# is a FAMILY, so the fold may name derived_from_1 AND _2.
    # #63 has not put a maximum on it; assert there is none, so a future cap
    # cannot land silently under a fold that emits two.
    dfrom = next(d for d in BUILT["subject_calculation"][1]["depends_on"]
                 if d["name"] == "derived_from_#")
    assert "max_count" not in dfrom or dfrom["max_count"] is None


