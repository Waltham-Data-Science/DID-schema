// The binding registry meta-file (schemas/V_*/stable/binding_registry_meta.json).
// Maps a statement's `variable` to the admissible value_set for its term value,
// and declares the kind-defining variables whose presence marks a subject's kind
// (D9). Only present from V_eta on; absent sets simply have no registry to browse.
// An ontology node reference: a CURIE plus a human-readable label snapshot.
export interface NodeRef {
  node: string;
  name: string;
}

// A subject_statement binding: variable (+ method) -> the concrete leaf `class`
// that carries the statement. The leaf fixes the value type (no data_type); a
// term-valued leaf additionally pins an admissible set — `values` (each an ontology
// term NodeRef) or an ontology subtree (ontology + root_node). `subject_defining`
// flags the kind-defining rows (the D9 ingest invariant). Shape is intentionally
// open; the browser renders whatever columns are present.
export interface Binding {
  variable?: NodeRef;
  method?: NodeRef;
  class?: string;
  values?: Array<NodeRef | string>;
  ontology?: string;
  root_node?: string;
  subject_defining?: boolean;
  notes?: string;
  [k: string]: unknown;
}

// A D6 relation binding: the admissible value on directed_relation.relation /
// undirected_relation.relation, pinned to its carrier `class` with typed endpoints.
// `relation` is a {node, name} NodeRef (same shape as a binding's variable/method).
// A directed_relation carries child_types/parent_types (matching the schema
// child/parent deps); an undirected_relation carries a symmetric member_types
// (reserved — no undirected term exists yet).
export interface RelationTerm {
  relation: NodeRef;
  class: string; // "directed_relation" | "undirected_relation"
  child_role?: string;
  parent_role?: string;
  child_types?: string[];
  parent_types?: string[];
  member_types?: string[];
  ordered?: boolean;
  timed?: boolean;
  [k: string]: unknown;
}

export interface BindingRegistryMeta {
  title?: string;
  description?: string;
  subject_statement_bindings?: Binding[];
  binding_examples?: Binding[];
  relation_bindings?: RelationTerm[];
  notes?: string;
  [k: string]: unknown;
}

// Inside a schema file, `superclasses` is an array of objects with at least
// a `class_name` key. The repo-level index.json normalizes these to plain
// strings, so callers may see either shape -- always pass through
// `superclassName()` to extract the string.
export type SuperclassRef = string | { class_name: string; [k: string]: unknown };

export function superclassName(ref: SuperclassRef): string {
  return typeof ref === "string" ? ref : ref.class_name;
}
