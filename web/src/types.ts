// V_eta migration coverage ledger (generated by tools/coverage.py, served as
// public/coverage.json). One row per did_v1 SOURCE class with its V_eta fate.
export interface CoverageRow {
  v1_class: string;
  veta_class: string | null; // null => no same-name V_eta class (dissolved/unmapped)
  disposition: string; // persist | retire | in_progress | a dissolved/unmapped label
  migrator: boolean; // a bespoke migrator consumes it (else base/passthrough)
  source: "ndi" | "app"; // NDI production template vs vhlab app/calculator class
  nonprod: boolean; // NDI test/demo scaffolding, not real corpus data
  gap: boolean; // no V_eta home, no migrator, never reviewed -> actionable hole
  // Migration TARGETS: the V_eta document class(es) the migrator emits.
  targets: string[]; // pass-1 emitted classes (or [same-name] when passthrough)
  // WHERE `targets` CAME FROM. Three different claims that used to render the
  // same way: "emitted" is measured from the migrators; "passthrough" means no
  // migrator exists and the document lands on the same-name class, which is
  // NOT a statement about where the class is going; "unknown" means neither.
  // "uncurated" is the actionable one: a migrator DOES run, but nothing
  // records what it emits -- a missing row in V_eta_migration_targets.json.
  // `decided` added 2026-08-10: the disposition is signed but NO migrator emits
  // it yet, so `targets` is empty and `decided_targets` carries what it WILL
  // become. Keeping them in separate fields is deliberate -- the ledger must
  // never let a decided target read as a produced one.
  target_source: "emitted" | "decided" | "uncurated" | "passthrough" | "unknown";
  decided_targets: string[]; // signed destination; nothing emits it yet
  carried: string[]; // pre-existing classes the emitted statements attach to (not minted)
  second_pass: string[]; // classes minted in the NDI second pass
  how: string; // one-line authored intent
  target_flags: string; // caveats: dynamic emit, header/code mismatch, deferrals
  // BUILD STATE -- computed by tools/coverage.py, committed in the ledger, and
  // rendered by NOTHING until the class-detail view: 0 occurrences of
  // `build_state` in this app before 2026-08-12. It splits a question the
  // `fate` badge runs together -- is the SCHEMA there, and does a MIGRATOR
  // emit it -- which were true of different halves for different classes.
  build_state?: BuildState;
  // A signed decision names targets; `decided_targets_source` says where that
  // naming came from and `decided_signoff` is the signature line itself. Both
  // were in the ledger and neither reached a reader.
  decided_targets_source?: string | null;
  decided_signoff?: string | null;
  no_target_reason?: string | null;
  no_target_account?: string | null;
  no_target_signoff?: string | null;
  // NARROWER than the retired `gap`: no target AND no dissolution recorded --
  // a gap, not a decision. Also rendered by nothing until now.
  target_gap?: boolean;
  // A DERIVED MIGRATION STAGE (a 0-5 ladder) is being added to the ledger by
  // another generator. It is typed permissively and rendered only if present,
  // because guessing its shape and rendering a wrong ladder would be worse
  // than rendering none: this viewer must not invent a field's meaning. A bare
  // number, or an object carrying a level and a label, are both understood;
  // anything else is shown as raw JSON rather than silently dropped.
  stage?: number | Record<string, unknown> | null;
  // WHY an empty `decided_targets` is empty. Four causes, and they are not
  // interchangeable: a signed dissolution (no target IS the answer), a signed
  // passthrough, a DISPUTED row where the record states two incompatible
  // dispositions, and a genuine gap where nothing was ever recorded. The
  // viewer rendered all four as "it dissolves or is deleted" -- asserting a
  // decision on behalf of rows where none exists. Absent on older ledgers,
  // which must render as UNKNOWN rather than falling back to the old claim.
  no_target_reason_label?: string | null;
}

// `build_state`, in full. Two independent halves, deliberately not summed into
// a single "done" flag: `schema_targets_built` is about this repository and
// `migrator_emits_decided_targets` is about DID-matlab, and for several classes
// exactly one of them is true.
export interface BuildState {
  schema_targets_named: number;
  schema_targets_built: string[];
  schema_targets_missing: string[];
  migrator_emits_decided_targets: boolean;
  has_per_class_migrator: boolean;
}

