// Copies every versioned schema set (schemas/V_* and schemas/did_v*) that has an index.json into
// web/public/schemas/<set>, and writes a versions.json manifest the app uses
// to populate the set-version selector. Runs automatically before `npm run
// dev` and `npm run build`.
//
// THE did_v2 LAYOUT ([schema folders by family], did_v2_go_forward_class_audit.md):
// schemas/did_v2/ holds class files only, in family folders; its index.json is
// schemas/generated/index.json, and the registries the index lists (its
// `is_meta` rows) live in schemas/registry/ and schemas/generated/. A set
// whose index.json is not in its own folder is selected when the generated
// index names it (`set_version`). The app reads a set's index, topics and
// meta-schema from public/schemas/<set>/, so those three are copied there, and
// each registry the index lists is served at the path the index gives it.
import { cp, rm, mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..", "..");
const schemasDir = resolve(repoRoot, "schemas");
const publicDir = resolve(here, "..", "public");
const publicSchemas = resolve(publicDir, "schemas");

// Set versions are named after Greek letters; order them so the newest set is
// the default. Unknown names sort after the known ones, then alphabetically.
const GREEK = [
  "alpha", "beta", "gamma", "delta", "epsilon", "zeta", "eta", "theta",
  "iota", "kappa", "lambda", "mu", "nu", "xi", "omicron", "pi",
];
// did_v<N> sets (the V_eta set was renamed did_v2, 2026-10-26) are unknown to
// GREEK and so sort last, which makes did_v2 the default.
function rank(name) {
  const m = /^V_([a-z]+)$/.exec(name);
  const i = m ? GREEK.indexOf(m[1]) : -1;
  return i === -1 ? 999 : i;
}

// The generated index, and the set it describes.
const indexSrc = resolve(schemasDir, "generated/index.json");
const generatedIndex = existsSync(indexSrc)
  ? JSON.parse(await readFile(indexSrc, "utf8"))
  : null;
const generatedSet = generatedIndex ? generatedIndex.set_version : null;

const entries = await readdir(schemasDir, { withFileTypes: true });
const versions = entries
  .filter(
    (d) =>
      d.isDirectory() &&
      /^(V_|did_v)/.test(d.name) &&
      (existsSync(resolve(schemasDir, d.name, "index.json")) || d.name === generatedSet),
  )
  .map((d) => d.name)
  .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));

if (versions.length === 0) {
  console.error(`sync-schemas: no V_* schema sets with index.json under ${schemasDir}`);
  process.exit(1);
}

await rm(publicSchemas, { recursive: true, force: true });
await mkdir(publicSchemas, { recursive: true });
for (const v of versions) {
  await cp(resolve(schemasDir, v), resolve(publicSchemas, v), { recursive: true });
  console.log(`sync-schemas: copied ${v}`);
}

// The did_v2 set's index, topic tree and meta-schema, served inside the set
// folder where the app fetches them.
const topicsSrc = resolve(schemasDir, "registry/topics.json");
const metaSchemaSrc = resolve(schemasDir, "registry/did_schema_meta.json");
if (generatedSet === "did_v2") {
  await cp(indexSrc, resolve(publicDir, "schemas/did_v2/index.json"));
  await cp(topicsSrc, resolve(publicDir, "schemas/did_v2/topics.json"));
  await cp(metaSchemaSrc, resolve(publicDir, "schemas/did_v2/did_schema_meta.json"));
  console.log("sync-schemas: copied generated/index.json, registry/topics.json, registry/did_schema_meta.json -> did_v2/");
}

// Every registry the generated index lists (an `is_meta` row), served at the
// path the index gives it, under one of these folders.
const DATA_DIRS = ["registry", "generated"];
let registries = 0;
for (const e of generatedIndex ? generatedIndex.schemas : []) {
  const parts = e.is_meta ? String(e.path).split("/") : [];
  if (parts.length === 3 && parts[0] === "schemas" && DATA_DIRS.includes(parts[1])) {
    await mkdir(resolve(publicSchemas, parts[1]), { recursive: true });
    await cp(resolve(schemasDir, parts[1], parts[2]), resolve(publicSchemas, parts[1], parts[2]));
    registries += 1;
  }
}
console.log(`sync-schemas: copied ${registries} registr(y/ies) the index lists`);

const defaultVersion = versions[versions.length - 1];
await writeFile(
  resolve(publicSchemas, "versions.json"),
  JSON.stringify({ versions, default: defaultVersion }, null, 2) + "\n",
);
console.log(
  `sync-schemas: ${versions.length} set(s) [${versions.join(", ")}], default ${defaultVersion}`,
);

// The V_eta migration coverage ledger (generated by tools/coverage.py) powers the
// Coverage panel. Copy the machine-readable JSON to public/coverage.json so the app
// can fetch it. Non-fatal if absent (older checkout / coverage.py not yet run).
const ledgerSrc = resolve(schemasDir, "generated/did_v2_coverage_ledger.json");
if (existsSync(ledgerSrc)) {
  await cp(ledgerSrc, resolve(publicDir, "coverage.json"));
  console.log("sync-schemas: copied did_v2_coverage_ledger.json -> coverage.json");
} else {
  console.warn("sync-schemas: no did_v2_coverage_ledger.json (run tools/coverage.py)");
}

// The decision families (generated by tools/status_board.py). The ledger says
// what a class's disposition IS; this says whether the model behind it has been
// decided and signed off. Without it the viewer showed a settled, signed family
// awaiting build as plain `in_progress` -- indistinguishable from undecided.
const decisionsSrc = resolve(schemasDir, "generated/did_v2_decisions.json");
if (existsSync(decisionsSrc)) {
  await cp(decisionsSrc, resolve(publicDir, "decisions.json"));
  console.log("sync-schemas: copied did_v2_decisions.json -> decisions.json");
} else {
  console.warn("sync-schemas: no did_v2_decisions.json (run tools/status_board.py)");
}
